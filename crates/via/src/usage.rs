/// HID usage of F13 (F13..F24 are consecutive).
pub const F13: u8 = 0x68;

pub fn to_scan(usage: u8) -> Option<(u16, bool)> {
    TABLE.iter().find(|e| e.0 == usage).map(|e| (e.1, e.2))
}

pub fn from_scan(scan: u16, ext: bool) -> Option<u8> {
    // Backslash and ISO # share a scan code; prefer the ANSI one.
    TABLE.iter().find(|e| e.1 == scan && e.2 == ext).map(|e| e.0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips() {
        for &(usage, scan, ext) in TABLE {
            if usage == 0x32 {
                continue;
            }
            assert_eq!(to_scan(usage), Some((scan, ext)));
            assert_eq!(from_scan(scan, ext), Some(usage), "usage {usage:#04x}");
        }
    }

    #[test]
    fn function_keys() {
        assert_eq!(to_scan(F13), Some((0x64, false)));
        assert_eq!(to_scan(F13 + 11), Some((0x76, false)));
    }
}
